#!/usr/bin/env node
/**
 * Keeps the iOS engine version in step with the package manifest.
 *
 * Android reads `package.json` directly from Gradle, but there is no equally
 * clean hook on the iOS side: CocoaPods `prepare_command` does not run for
 * path-based development pods, and Swift compilation conditions cannot carry
 * string values. Generating a one-line header and checking it into the
 * repository keeps a single source of truth without build-system contortions.
 *
 * Usage:
 *   node scripts/sync-native-version.mjs          # write the header
 *   node scripts/sync-native-version.mjs --check  # fail if it is stale (CI)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const packagePath = join(root, 'packages/runtime/package.json');
const headerPath = join(root, 'packages/runtime/ios/SecurityToolkitVersion.h');

const { version } = JSON.parse(readFileSync(packagePath, 'utf8'));

const header = `// Generated by scripts/sync-native-version.mjs — do not edit by hand.
// Source of truth: packages/runtime/package.json
#pragma once

#define RNSEC_ENGINE_VERSION "${version}"
`;

const checkOnly = process.argv.includes('--check');
const existing = (() => {
  try {
    return readFileSync(headerPath, 'utf8');
  } catch {
    return null;
  }
})();

if (existing === header) {
  console.log(`Native engine version is in sync (${version}).`);
  process.exit(0);
}

if (checkOnly) {
  console.error(
    `SecurityToolkitVersion.h is out of date (expected version ${version}).\n` +
      'Run: node scripts/sync-native-version.mjs'
  );
  process.exit(1);
}

writeFileSync(headerPath, header);
console.log(`Wrote ${headerPath} (${version}).`);
